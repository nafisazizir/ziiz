"""Requires Python 3 + fonttools (pip install fonttools). No fonts are vendored."""

import io
import json
import os
from pathlib import Path
import string
import tempfile
import urllib.request
import zipfile

from fontTools.ttLib import TTFont
from fontTools.t1Lib import T1Font
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.recordingPen import RecordingPen

from sharpen_letters import contours, sharpen_contour, samples

ROOT = Path(__file__).resolve().parents[1]
LM = Path(os.environ.get("LM_FONT_DIR", "/usr/share/texmf/fonts/opentype/public/lm"))
MATH = Path(
    os.environ.get("LM_MATH_FONT", str(LM.parent / "lm-math/latinmodern-math.otf"))
)
LETTERS = string.ascii_uppercase + string.ascii_lowercase


def outlines(glyphs, mapping, sharp=False):
    bounds = BoundsPen(glyphs)
    glyphs[mapping["H"]].draw(bounds)
    scale = 600 / bounds.bounds[3]
    result = {}
    for letter, name in mapping.items():
        if name not in glyphs:
            continue
        bounds = BoundsPen(glyphs)
        glyphs[name].draw(bounds)
        if not bounds.bounds:
            continue
        x0, _, x1, _ = bounds.bounds
        pen = SVGPathPen(glyphs, ntos=lambda n: str(round(n, 3)))
        target = TransformPen(
            pen, (scale, 0, 0, -scale, 500 - (x0 + x1) * scale / 2, 800)
        )
        if sharp:
            recording = RecordingPen()
            glyphs[name].draw(recording)
            shapes = contours(recording.value)
            ys = [p[1] for c in shapes for s in c for p in samples(s)]
            for contour in shapes:
                contour = sharpen_contour(contour, "clip", (min(ys), max(ys)))
                target.moveTo(contour[0][0])
                for _, op, points in contour:
                    getattr(target, op)(*points)
                target.closePath()
        else:
            glyphs[name].draw(target)
        result[letter] = pen.getCommands()
    return result


def otf(path, codes, sharp=False):
    font = TTFont(path)
    cmap = font.getBestCmap()
    return outlines(
        font.getGlyphSet(),
        {letter: cmap[code] for letter, code in codes.items() if code in cmap},
        sharp,
    )


plain = {letter: ord(letter) for letter in LETTERS}
italic = {
    letter: (0x1D434 + i if i < 26 else 0x1D44E + i - 26)
    for i, letter in enumerate(LETTERS)
}
italic["h"] = 0x210E
blackboard = {
    letter: (0x1D538 + i if i < 26 else 0x1D552 + i - 26)
    for i, letter in enumerate(LETTERS)
}
blackboard.update(
    dict(zip("CHNPQRZ", [0x2102, 0x210D, 0x2115, 0x2119, 0x211A, 0x211D, 0x2124]))
)
data = [
    {
        "id": "sharp-blackboard",
        "label": "Sharp blackboard",
        "family": "Double stroke",
        "glyphs": otf(MATH, blackboard, sharp=True),
    },
    {
        "id": "cm-roman",
        "label": "Roman",
        "family": "Computer Modern",
        "glyphs": otf(LM / "lmroman10-regular.otf", plain),
    },
    {
        "id": "cm-italic",
        "label": "Math italic",
        "family": "Computer Modern",
        "glyphs": otf(MATH, italic),
    },
    {
        "id": "cm-bold",
        "label": "Bold",
        "family": "Computer Modern",
        "glyphs": otf(LM / "lmroman10-bold.otf", plain),
    },
    {
        "id": "cm-mathbb",
        "label": "Math blackboard",
        "family": "Computer Modern double stroke",
        "glyphs": otf(MATH, blackboard),
    },
]
archive = zipfile.ZipFile(
    io.BytesIO(
        urllib.request.urlopen("https://mirrors.ctan.org/fonts/doublestroke.zip").read()
    )
)
with tempfile.TemporaryDirectory() as directory:
    for name, label in [("dsrom10", "dsfont Roman"), ("dsss10", "dsfont Sans")]:
        path = Path(directory) / (name + ".pfb")
        path.write_bytes(archive.read("doublestroke/" + name + ".pfb"))
        font = T1Font(str(path))
        glyphs = font.getGlyphSet()
        encoding = font["Encoding"]
        mapping = {
            letter: encoding[ord(letter)]
            for letter in LETTERS
            if encoding[ord(letter)] != ".notdef"
        }
        data.append(
            {
                "id": name,
                "label": label,
                "family": "Computer Modern double stroke",
                "glyphs": outlines(glyphs, mapping),
            }
        )

output = "// Generated by scripts/generate-letters.py. Do not edit.\n"
output += "export type LetterStyle = { id: string; label: string; family: string; glyphs: Record<string, string> }\n"
output += (
    "export const letterStyles: LetterStyle[] = "
    + json.dumps(data, ensure_ascii=False, indent=2)
    + "\n"
)
(ROOT / "lib/letters/glyphs.ts").write_text(output)
for style in data:
    print(style["id"], len(style["glyphs"]), "glyphs")
